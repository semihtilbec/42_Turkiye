int	is_valid_number(char *str)
{
	int	i;

	i = 0;
	if (str[i])
	{
		if (str[i] == '-' || str[i] == '+')
			i++;
		if (str[i] >= '0' && str[i] <= '9')
			return (1);
		return (0);
	}
}
